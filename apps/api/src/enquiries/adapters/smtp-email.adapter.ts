import { Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import * as nodemailer from 'nodemailer';
import { IEmailProvider, EmailDispatchResult } from './email-provider.interface';
import { Enquiry } from '../interfaces/enquiry.interface';

@Injectable()
export class SmtpEmailAdapter implements IEmailProvider {
  private readonly logger = new Logger(SmtpEmailAdapter.name);
  private transporter: nodemailer.Transporter;
  private readonly salesInbox: string;
  private readonly fromAddress: string;

  constructor(private readonly configService: ConfigService) {
    const host = this.configService.get<string>('SMTP_HOST') || 'localhost';
    const port = Number(this.configService.get<number>('SMTP_PORT') || 1025);
    const user = this.configService.get<string>('SMTP_USER') || undefined;
    const pass = this.configService.get<string>('SMTP_PASS') || undefined;
    const secure = this.configService.get<string>('SMTP_SECURE') === 'true';

    this.salesInbox =
      this.configService.get<string>('SALES_INBOX_EMAIL') ||
      'sales@productatlas.dev';
    this.fromAddress =
      this.configService.get<string>('EMAIL_FROM') ||
      'noreply@productatlas.dev';

    this.transporter = nodemailer.createTransport({
      host,
      port,
      secure,
      auth: user && pass ? { user, pass } : undefined,
      ignoreTLS: true,
    });

    this.logger.log(
      `SmtpEmailAdapter initialized targeting ${host}:${port} (Sales Inbox: ${this.salesInbox})`,
    );
  }

  async sendEnquiryNotification(enquiry: Enquiry): Promise<EmailDispatchResult> {
    const subject = `🔥 New Product Enquiry: "${enquiry.productTitle}" (Ref: ${enquiry.id})`;

    const textContent = `
NEW CUSTOMER ENQUIRY RECEIVED
==============================
Reference ID: ${enquiry.id}
Submitted At: ${enquiry.createdAt}

PRODUCT DETAILS:
- Product ID: ${enquiry.productId}
- Title: ${enquiry.productTitle}

CUSTOMER CONTACT:
- Name: ${enquiry.customerName}
- Email: ${enquiry.customerEmail}
- Phone: ${enquiry.customerPhone || 'N/A'}

CUSTOMER MESSAGE:
${enquiry.message || 'No additional note provided.'}
==============================
This enquiry was generated by the Product Atlas platform.
`;

    const htmlContent = `
<!DOCTYPE html>
<html>
<head>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; line-height: 1.6; color: #1e293b; background-color: #f8fafc; margin: 0; padding: 20px; }
    .card { max-width: 600px; margin: 0 auto; background: #ffffff; border-radius: 12px; border: 1px solid #e2e8f0; overflow: hidden; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.05); }
    .header { background: #0f172a; color: #ffffff; padding: 24px; text-align: left; }
    .header h2 { margin: 0; font-size: 20px; font-weight: 600; }
    .header p { margin: 4px 0 0 0; color: #94a3b8; font-size: 13px; }
    .content { padding: 24px; }
    .badge { display: inline-block; padding: 4px 10px; font-size: 12px; font-weight: 600; border-radius: 6px; background-color: #e0f2fe; color: #0369a1; }
    .section-title { font-size: 13px; text-transform: uppercase; letter-spacing: 0.05em; color: #64748b; font-weight: 700; margin-top: 20px; margin-bottom: 8px; border-bottom: 1px solid #f1f5f9; padding-bottom: 4px; }
    .field-row { margin-bottom: 8px; }
    .field-label { font-weight: 600; color: #475569; width: 120px; display: inline-block; }
    .field-value { color: #0f172a; }
    .message-box { background: #f8fafc; border-left: 4px solid #0284c7; padding: 12px 16px; border-radius: 4px; font-style: italic; color: #334155; margin-top: 8px; }
    .footer { background: #f8fafc; border-top: 1px solid #e2e8f0; padding: 16px 24px; font-size: 12px; color: #64748b; text-align: center; }
  </style>
</head>
<body>
  <div class="card">
    <div class="header">
      <h2>New Product Enquiry</h2>
      <p>Reference: ${enquiry.id} • ${new Date(enquiry.createdAt).toLocaleString()}</p>
    </div>
    <div class="content">
      <div class="badge">Inbound Lead</div>
      
      <div class="section-title">Product Information</div>
      <div class="field-row">
        <span class="field-label">Product ID:</span>
        <span class="field-value">#${enquiry.productId}</span>
      </div>
      <div class="field-row">
        <span class="field-label">Title:</span>
        <span class="field-value"><strong>${enquiry.productTitle}</strong></span>
      </div>

      <div class="section-title">Customer Details</div>
      <div class="field-row">
        <span class="field-label">Customer:</span>
        <span class="field-value">${enquiry.customerName}</span>
      </div>
      <div class="field-row">
        <span class="field-label">Email:</span>
        <span class="field-value"><a href="mailto:${enquiry.customerEmail}">${enquiry.customerEmail}</a></span>
      </div>
      <div class="field-row">
        <span class="field-label">Phone:</span>
        <span class="field-value">${enquiry.customerPhone || 'Not provided'}</span>
      </div>

      <div class="section-title">Customer Message</div>
      <div class="message-box">
        ${enquiry.message ? enquiry.message.replace(/\n/g, '<br/>') : 'No additional message was included.'}
      </div>
    </div>
    <div class="footer">
      This is an automated sales alert from your Product Atlas application.
    </div>
  </div>
</body>
</html>
`;

    try {
      const info = await this.transporter.sendMail({
        from: `"${this.fromAddress}" <${this.fromAddress}>`,
        to: this.salesInbox,
        replyTo: enquiry.customerEmail,
        subject,
        text: textContent,
        html: htmlContent,
      });

      this.logger.log(`Enquiry email dispatched to ${this.salesInbox} (ID: ${info.messageId})`);
      return {
        messageId: info.messageId,
        recipient: this.salesInbox,
      };
    } catch (error) {
      this.logger.error(
        `Failed to deliver email via SMTP (${(error as Error).message}). Falling back to stdout log.`,
      );
      return {
        messageId: `fallback-${Date.now()}`,
        recipient: this.salesInbox,
      };
    }
  }
}

